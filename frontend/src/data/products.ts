const IMAGE_CAPTIONS = ["studio view", "styled at home", "close detail"] as const;

function buildImages(seed: ProductSeed): ProductImage[] {
  return IMAGE_CAPTIONS.map((caption, index) => ({
    id: `${seed.slug}-${index + 1}`,
    src: `/images/products/${seed.slug}-${index + 1}.svg`,
    alt: `${seed.name} — ${caption}`,
    width: 1000,
    height: 1250,
  }));
}

function resolveBadge(seed: ProductSeed): ProductBadge | null {
  if (seed.badge) return seed.badge;
  if (seed.isNew) return "new";
  if (seed.isBestSeller) return "bestseller";
  if (seed.compareAtPrice) return "sale";
  return null;
}

function toProduct(seed: ProductSeed, index: number): Product {
  return {
    id: `p-${String(index + 1).padStart(3, "0")}`,
    slug: seed.slug,
    name: seed.name,
    shortDescription: seed.shortDescription,
    description: seed.description,
    details: seed.details,
    price: seed.price,
    compareAtPrice: seed.compareAtPrice ?? null,
    category: seed.category,
    occasions: seed.occasions,
    recipients: seed.recipients,
    colors: seed.colors,
    images: buildImages(seed),
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    badge: resolveBadge(seed),
    isNew: seed.isNew ?? false,
    isFeatured: seed.isFeatured ?? false,
    isBestSeller: seed.isBestSeller ?? false,
    isPersonalized: Boolean(seed.personalization),
    tags: seed.tags,
    stock: seed.stock,
    variants: seed.variants ?? [],
    personalization: seed.personalization ?? null,
    materials: seed.materials,
    dimensions: seed.dimensions,
    createdAt: seed.createdAt,
  };
}

export const products: readonly Product[] = seeds.map(toProduct);

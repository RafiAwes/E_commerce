const ENGRAVING_STYLES: readonly PersonalizationStyle[] = [
  { id: "script", name: "Flowing Script", previewFontClass: "font-display italic" },
  { id: "serif", name: "Classic Serif", previewFontClass: "font-display" },
  { id: "modern", name: "Modern Sans", previewFontClass: "font-sans uppercase tracking-[0.22em]" },
];

function engraving(
  surface: PersonalizationSpec["surface"],
  overrides: Partial<PersonalizationSpec> = {},
): PersonalizationSpec {
  return {
    nameLabel: "Name to engrave",
    namePlaceholder: "e.g. Amina & Rafi",
    maxNameLength: 20,
    supportsMessage: true,
    maxMessageLength: 70,
    styles: ENGRAVING_STYLES,
    surface,
    ...overrides,
  };
}


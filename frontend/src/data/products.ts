/**
 * The single source of catalogue truth for the prototype.
 *
 * Products are authored as compact seeds and expanded by `toProduct` so the
 * repetitive parts (image paths, alt text, derived flags) stay consistent
 * across all thirty items. A real backend would return `Product` directly;
 * only `repositories/product` needs to change.
 */

interface ProductSeed {
  slug: string;
  name: string;
  category: CategoryId;
  price: number;
  compareAtPrice?: number;
  shortDescription: string;
  description: string;
  details: string[];
  occasions: OccasionId[];
  recipients: RecipientId[];
  colors: ColorId[];
  rating: number;
  reviewCount: number;
  badge?: ProductBadge;
  isNew?: boolean;
  isFeatured?: boolean;
  isBestSeller?: boolean;
  personalization?: PersonalizationSpec;
  variants?: ProductVariant[];
  tags: string[];
  stock: number;
  materials: string;
  dimensions: string;
  createdAt: string;
}

